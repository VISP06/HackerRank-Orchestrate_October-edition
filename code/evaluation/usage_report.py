"""Generate the token/cost report for the current full run.

The current usage log is intentionally the only source for final-run usage
figures. The archived development log is shown separately for transparency.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
FINAL_LOG = ROOT / "code" / "llm_cache" / "usage_log.jsonl"
DEV_LOG = ROOT / "notes" / "archive" / "usage_log_development.jsonl"
PRICING = ROOT / "code" / "ghost" / "llm_pricing.json"
REPORT = ROOT / "code" / "evaluation" / "usage_report.md"
REQUEST_COUNT = 518


def read_log(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def summarize(rows: list[dict], pricing: dict) -> dict:
    models_pricing = pricing.get("models", {})
    tasks = defaultdict(lambda: {"calls": 0, "cache_hits": 0, "input": 0, "output": 0, "cost": 0.0})
    models = defaultdict(lambda: {"calls": 0, "cache_hits": 0, "input": 0, "output": 0, "cost": 0.0})
    for row in rows:
        task = tasks[row.get("task", "unknown")]
        model = models[row.get("model", "unknown")]
        cached = bool(row.get("cached", False))
        for bucket in (task, model):
            bucket["calls"] += 1
            bucket["cache_hits"] += int(cached)
            bucket["input"] += int(row.get("input_tokens", 0))
            bucket["output"] += int(row.get("output_tokens", 0))
        rates = models_pricing.get(row.get("model", ""), models_pricing.get("default", {}))
        row_cost = (int(row.get("input_tokens", 0)) * rates.get("input_per_1m", 0) + int(row.get("output_tokens", 0)) * rates.get("output_per_1m", 0)) / 1_000_000
        task["cost"] += row_cost
        model["cost"] += row_cost
    return {"tasks": dict(tasks), "models": dict(models)}


def cost(bucket: dict, rates: dict) -> float:
    return bucket["input"] * rates.get("input_per_1m", 0) / 1_000_000 + bucket["output"] * rates.get("output_per_1m", 0) / 1_000_000


def money(value: float) -> str:
    return f"${value:.6f}"


def task_label(task: str) -> str:
    return {
        "screenshot_extract": "Screenshots",
        "pdf_extract": "PDFs",
        "intent_classify": "Intent",
    }.get(task, task)


def render_table(summary: dict, pricing: dict) -> tuple[str, float, int, int]:
    models = pricing.get("models", {})
    lines = [
        "| Task | Calls | Cache hits | Input tokens | Output tokens | Total tokens | Estimated cost |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    total_cost = total_in = total_out = 0
    for task in ("screenshot_extract", "pdf_extract", "intent_classify"):
        bucket = summary["tasks"].get(task, {"calls": 0, "cache_hits": 0, "input": 0, "output": 0})
        value = bucket["cost"]
        total_in += bucket["input"]
        total_out += bucket["output"]
        total_cost += value
        lines.append(f"| {task_label(task)} | {bucket['calls']} | {bucket['cache_hits']} | {bucket['input']:,} | {bucket['output']:,} | {bucket['input'] + bucket['output']:,} | {money(value)} |")
    lines.append(f"| **Overall** | **{sum(x['calls'] for x in summary['tasks'].values())}** | **{sum(x['cache_hits'] for x in summary['tasks'].values())}** | **{total_in:,}** | **{total_out:,}** | **{total_in + total_out:,}** | **{money(total_cost)}** |")
    return "\n".join(lines), total_cost, total_in, total_out


def main() -> None:
    rows = read_log(FINAL_LOG)
    development = read_log(DEV_LOG)
    pricing = json.loads(PRICING.read_text(encoding="utf-8"))
    summary = summarize(rows, pricing)
    table, total_cost, total_in, total_out = render_table(summary, pricing)
    models = pricing.get("models", {})
    source = pricing.get("_source", "pricing file")
    checked = pricing.get("_checked", str(date.today()))
    model_names = ", ".join(sorted(summary["models"])) or "none"
    report = [
        "# Usage Report — Authoritative Fresh Full Run",
        "",
        "## Final run source and scope",
        "",
        "This report is generated by `code/evaluation/usage_report.py` from the current `code/llm_cache/usage_log.jsonl`; no final-run token or cost figures are hand-entered.",
        f"The run contains **{len(rows)}** logged model calls for all **{REQUEST_COUNT}** requests. Provider: **Google Gemini API** (`google-genai`). Exact model(s): **{model_names}**.",
        "Deterministic loading, linking, state reconstruction, policy evaluation, step generation, validation, and CSV writing use no model tokens.",
        "",
        f"Pricing source: [{source}]({source}), checked **{checked}**, using the rates in `code/ghost/llm_pricing.json`.",
        "",
        "## Final full-run usage",
        "",
        table,
        "",
        f"- Total tokens: **{total_in + total_out:,}** ({total_in:,} input + {total_out:,} output).",
        f"- Mean tokens per request: **{(total_in + total_out) / REQUEST_COUNT:.2f}**.",
        f"- Estimated total cost: **{money(total_cost)}**; estimated cost per request: **{money(total_cost / REQUEST_COUNT)}**.",
        "- Cache-hit counts above are from the current log; a fresh run should have zero cache hits.",
        "",
        "### Per-model totals",
        "",
        "| Model | Calls | Cache hits | Input tokens | Output tokens | Total tokens | Estimated cost |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for model in sorted(summary["models"]):
        bucket = summary["models"][model]
        report.append(f"| `{model}` | {bucket['calls']} | {bucket['cache_hits']} | {bucket['input']:,} | {bucket['output']:,} | {bucket['input'] + bucket['output']:,} | {money(bucket['cost'])} |")
    report += [
        "",
        "## Development usage (not part of the final run)",
        "",
        "The following totals are generated from `notes/archive/usage_log_development.jsonl` and are retained only to make mixed development history transparent. They must not be added to the authoritative totals above.",
    ]
    dev_summary = summarize(development, pricing)
    dev_table, dev_cost, dev_in, dev_out = render_table(dev_summary, pricing)
    report += [dev_table, "", f"Development totals: {dev_in + dev_out:,} tokens across {len(development)} calls; estimated cost {money(dev_cost)}.", ""]
    REPORT.write_text("\n".join(report), encoding="utf-8")


if __name__ == "__main__":
    main()
